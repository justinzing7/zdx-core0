#!/usr/bin/env python3
"""ZDX CORE-0 asset converter: PNG -> 1-bpp core0::Bitmap headers.

Usage:
  python tools/img2c.py                       # convert everything under assets/src
  python tools/img2c.py --src assets/src --out src/assets/gen --threshold 128 --invert

  assets/src/<name>.png             -> src/assets/gen/<name>.h       (kBmp<Name>)
  assets/src/anim/<name>/*.png      -> src/assets/gen/anim_<name>.h  (frames + kAnim<Name>)
  optional assets/src/anim/<name>/anim.json: {"hold_ms": 80, "loop": false, "holds": [..]}

Pixel ON (drawn) = dark pixels by default; --invert for light-on-dark source art.
Requires Pillow (pip install pillow). Output is deterministic (commit it).
"""
import argparse
import json
import re
from pathlib import Path

from PIL import Image


def camel(name: str) -> str:
    return "".join(p.capitalize() for p in re.split(r"[^0-9a-zA-Z]+", name) if p)


def ident(name: str) -> str:
    return re.sub(r"[^0-9a-zA-Z_]", "_", name)


def pack(img: Image.Image, threshold: int, invert: bool):
    g = img.convert("LA") if img.mode in ("LA", "RGBA", "PA") else img.convert("L")
    w, h = g.size
    px = g.load()
    out = []
    for y in range(h):
        byte, bit = 0, 7
        for x in range(w):
            p = px[x, y]
            lum, alpha = (p if isinstance(p, tuple) else (p, 255))
            on = alpha >= 128 and ((lum >= threshold) if invert else (lum < threshold))
            if on:
                byte |= 1 << bit
            bit -= 1
            if bit < 0:
                out.append(byte)
                byte, bit = 0, 7
        if bit != 7:
            out.append(byte)
    return w, h, out


def c_array(name: str, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    return f"static const uint8_t {name}[] = {{\n" + "\n".join(lines) + "\n};\n"


HEADER = "// Generated by tools/img2c.py — do not edit.\n#pragma once\n#include <core0/display.h>\n\n"


def convert_image(path: Path, out_dir: Path, a):
    w, h, data = pack(Image.open(path), a.threshold, a.invert)
    base = ident(path.stem)
    body = HEADER + c_array(f"kBmpData_{base}", data)
    body += f"static const core0::Bitmap kBmp{camel(path.stem)} = {{{w}, {h}, kBmpData_{base}}};\n"
    (out_dir / f"{path.stem}.h").write_text(body)
    return f"{path.name} -> {w}x{h}"


def convert_anim(folder: Path, out_dir: Path, a):
    frames = sorted(p for p in folder.glob("*.png"))
    if not frames:
        return None
    meta = {"hold_ms": 80, "loop": False}
    if (folder / "anim.json").exists():
        meta.update(json.loads((folder / "anim.json").read_text()))
    holds = meta.get("holds") or [meta["hold_ms"]] * len(frames)
    base, cname = ident(folder.name), camel(folder.name)
    body = HEADER
    for i, f in enumerate(frames):
        w, h, data = pack(Image.open(f), a.threshold, a.invert)
        body += c_array(f"kAnimData_{base}_{i}", data)
        body += f"static const core0::Bitmap kAnimBmp_{base}_{i} = {{{w}, {h}, kAnimData_{base}_{i}}};\n"
    body += f"static const core0::AnimFrame kAnimFrames_{base}[] = {{\n"
    for i in range(len(frames)):
        body += f"  {{&kAnimBmp_{base}_{i}, {int(holds[i])}}},\n"
    body += "};\n"
    loop = "true" if meta.get("loop") else "false"
    body = body.replace("#include <core0/display.h>", "#include <core0/anim.h>")
    body += f"static const core0::Animation kAnim{cname} = {{kAnimFrames_{base}, {len(frames)}, {loop}}};\n"
    (out_dir / f"anim_{folder.name}.h").write_text(body)
    return f"anim/{folder.name} -> {len(frames)} frames"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", default="assets/src")
    ap.add_argument("--out", default="src/assets/gen")
    ap.add_argument("--threshold", type=int, default=128)
    ap.add_argument("--invert", action="store_true")
    a = ap.parse_args()
    src, out = Path(a.src), Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for p in sorted(src.glob("*.png")):
        print(convert_image(p, out, a))
    anim_root = src / "anim"
    if anim_root.is_dir():
        for d in sorted(x for x in anim_root.iterdir() if x.is_dir()):
            r = convert_anim(d, out, a)
            if r:
                print(r)


if __name__ == "__main__":
    main()
